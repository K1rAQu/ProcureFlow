export const DICTIONARIES: Record<Locale, Messages> = { en, uk };

export function isLocale(value: string | undefined | null): value is Locale {
  return value === "en" || value === "uk";
}

export function getMessages(locale?: string): Messages {
  if (locale === "uk") return uk;
  return en;
}

export function translate(messages: Messages, key: string, fallbackMessages?: Messages): string {
  return messages[key] ?? fallbackMessages?.[key] ?? en[key] ?? uk[key] ?? key;
}

export function createTranslator(locale?: string) {
  const messages = getMessages(locale);
  const fallback = locale === "uk" ? en : uk;
  return (key: string) => translate(messages, key, fallback);
}

